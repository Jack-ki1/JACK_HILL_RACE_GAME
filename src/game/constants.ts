export function getStageById(id: StageId): StageConfig {
  return STAGES.find((s) => s.id === id) ?? STAGES[0];
}

export function getVehicleById(id: VehicleId): VehicleConfig {
  return VEHICLES.find((v) => v.id === id) ?? VEHICLES[0];
}

export function getUpgradeCost(key: UpgradeKey, currentLevel: number): number {
  const def = UPGRADE_DEFS.find((d) => d.key === key) ?? UPGRADE_DEFS[0];
  return def.baseCost + currentLevel * def.costStep;
}
